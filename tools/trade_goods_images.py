"""Validate commodity image provenance and regenerate the native picture map."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def build():
    goods = json.loads((ROOT / 'data/trade_goods.json').read_text(encoding='utf-8'))['goods']
    directory = ROOT / 'data/trade_goods'
    items = json.loads((directory / 'sources.json').read_text(encoding='utf-8'))['items']
    sources = {item['key']: item for item in items}
    assert len(sources) == len(items), 'duplicate image key'
    assert set(sources) == {g['key'] for g in goods}, 'image manifest and catalogue differ'
    rows = ['// Generated by tools/trade_goods_images.py; do not edit.']
    missing = []
    for g in goods:
        item = sources[g['key']]
        filename = item['file']
        assert Path(filename).name == filename and filename.isascii()
        assert item['name'] == g['name']
        if item.get('status') == 'missing':
            assert item.get('note') and not (directory / filename).exists()
            missing.append(g['name'])
        else:
            assert hashlib.sha256((directory / filename).read_bytes()).hexdigest() == item['sha256'], filename
        rows.append(f'    {{L"{g["name"]}",L"{filename}"}},')
    (ROOT / 'worldmod/src/trade_goods_images.inc').write_text('\n'.join(rows) + '\n', encoding='utf-8')
    print(f'{len(goods)} mappings, {len(goods)-len(missing)} verified images; missing: {missing}')


if __name__ == '__main__':
    build()
