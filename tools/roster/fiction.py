def desc_role(desc):
    """身份跟着列传文字走"""
    if any(w in desc for w in ("首領", "部帥", "酋長", "大人", "族長", "長老", "首長", "小王", "城主", "土豪", "豪族")):
        return "外族首领"
    if any(w in desc for w in ("祭司", "婆羅門", "經論", "哲學", "修辭")):
        return "名士"
    if any(w in desc for w in ("軍", "武士", "騎", "兵", "勇", "驍", "射", "獵", "長船", "將")):
        return "武将"
    return "文臣"


def make(city, n, used):
    """为城 city（cities.json 的一项）生成第 n 个虚构武将；used：已用名字集合（尽量不重名）"""
    cul = REGION_CULTURE.get(city["region"])
    if not cul:
        return None
    C = CULTURE[cul]
    key = f"fic:{city['id']}:{n}"
    for t in range(40):
        sei = C["sei"][rnd(key, f"sei{t}", len(C["sei"]))]
        mei = C["mei"][rnd(key, f"mei{t}", len(C["mei"]))]
        if len(sei) + len(mei) > 4:
            continue
        if sei + mei not in used:
            break
    used.add(sei + mei)
    desc = C["desc"][rnd(key, "desc", len(C["desc"]))].format(r=city["full"].split("(")[0])
    role = desc_role(desc)
    lean = C["lean"][rnd(key, "lean", len(C["lean"]))]
    if lean == "兵":
        lean = "兵器"
    base = {"武将": [62, 66, 45, 35, 48], "外族首领": [64, 68, 42, 38, 58], "文臣": [35, 30, 60, 66, 55],
            "宗室": [50, 45, 52, 52, 60], "名士": [25, 20, 68, 55, 64], "僧道": [20, 15, 66, 45, 62]}[role]
    stats = [max(10, min(85, b + rnd(key, f"s{i}", 25) - 12)) for i, b in enumerate(base)]
    birth = 150 + rnd(key, "birth", 190)
    return {"key": key, "name": sei + mei, "sei": sei, "mei": mei, "azana": "", "sex": 0, "birth": birth,
            "death": birth + 45 + rnd(key, "life", 25), "years": [birth + 18, birth + 50], "death_violent": False,
            "city": city["full"], "region": city["region"], "polity": C["polity"], "role": role, "offices": [],
            "kin": [], "friends": [], "foes": [], "bio": desc, "stats": stats, "lean": lean,
            "src": ["虛構（補位）"], "conf": "D", "fame": 0, "world": True, "culture": cul}
