CN_NUM = {"元": 1, "一": 1, "二": 2, "三": 3, "四": 4, "五": 5, "六": 6, "七": 7, "八": 8, "九": 9, "十": 10}
ERA_RE = re.compile("(" + "|".join(sorted(ERA, key=len, reverse=True)) + r")([元一二三四五六七八九十]{1,3})年")


def cn_int(s):
    if s == "元":
        return 1
    n = 0
    if "十" in s:
        a, _, b = s.partition("十")
        n = (CN_NUM.get(a, 1) if a else 1) * 10 + (CN_NUM.get(b, 0) if b else 0)
    else:
        n = CN_NUM.get(s, 0)
    return n


def era_years(text, polity=""):
    """文字里的「年号N年」→ 公元年列表（年号同名时按政权关键字选，选不出取第一个）"""
    out = []
    for m in ERA_RE.finditer(text or ""):
        opts = ERA.get(m.group(1)) or []
        hit = [y for y, kw in opts if kw and kw in (polity or "")] or [y for y, kw in opts]
        n = cn_int(m.group(2))
        if hit and 1 <= n <= 50:
            out.append(hit[0] + n - 1)
    return out


def ad_years(text, lo=100, hi=450):
    """「315年」「公元 268 年」这类公元年"""
    return [int(y) for y in re.findall(r"(?<![\d.])(\d{3})\s*年", text or "") if lo <= int(y) <= hi]


