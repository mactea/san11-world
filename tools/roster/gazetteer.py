JUN = {k: tuple(map(float, v.split(","))) for k, v in (x.split(":") for x in JUN.split())}


def _dist(a, b):
    la1, lo1, la2, lo2 = map(math.radians, (a[0], a[1], b[0], b[1]))
    h = math.sin((la2 - la1) / 2) ** 2 + math.cos(la1) * math.cos(la2) * math.sin((lo2 - lo1) / 2) ** 2
    return 6371 * 2 * math.asin(math.sqrt(h))


_cities = None


def cities():
    global _cities
    if _cities is None:
        _cities = load_json(SRC / "cities.json")
    return _cities


def nearest_city(lat, lon, china_only=False):
    best = None
    for c in cities():
        if china_only and not (c["koei"] or c["id"] >= 500):
            continue
        d = _dist((lat, lon), (c["lat"], c["lon"]))
        if best is None or d < best[0]:
            best = (d, c)
    return best[1]["full"], round(best[0])


_cbdb = None


def _county(name):
    global _cbdb
    if _cbdb is None:
        db = sqlite3.connect(CACHE / "cbdb_20261017.sqlite3")
        _cbdb = {}
        for n, fy, ly, x, y in db.execute("select c_name_chn, c_firstyear, c_lastyear, x_coord, y_coord from ADDR_CODES "
                                          "where x_coord is not null"):
            score = abs(((fy or 0) + (ly or 0)) / 2 - 250)          # 越接近三国两晋越好
            if n not in _cbdb or score < _cbdb[n][0]:
                _cbdb[n] = (score, (y, x))
    v = _cbdb.get(name)
    return v[1] if v else None


@lru_cache(maxsize=None)
def place_latlon(origin):
    """籍贯文字（简繁皆可）→ (lat, lon) 或 None"""
    if not origin:
        return None
    o = s2t(origin).strip()
    for n in (4, 3, 2, 1):                   # 郡名在前：安定朝那、琅邪陽都、南陽宛
        if len(o) >= n and o[:n] in JUN:
            return JUN[o[:n]]
    for n in (3, 2):                          # 县名在后
        if len(o) >= n and _county(o[-n:]):
            return _county(o[-n:])
    for n in (3, 2):
        if len(o) >= n and _county(o[:n]):
            return _county(o[:n])
    return None


def origin_city(origin, china_only=False):
    p = place_latlon(origin)
    if not p:
        return None
    return nearest_city(p[0], p[1], china_only=china_only)[0]
